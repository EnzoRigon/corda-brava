def rope_coil():
    s = sprite(16, 16)
    s.ellipse(1, 3, 14, 13, C["K"])
    s.ellipse(2, 4, 13, 12, C["T"])
    s.ellipse(2, 7, 13, 12, C["t"], only=C["T"])
    s.ellipse(2, 4, 13, 11, C["T"], only=C["t"]) if False else None
    s.ellipse(4, 5, 11, 10, C["K"])
    s.ellipse(5, 6, 10, 9, C["T"])
    s.ellipse(7, 7, 8, 8, C["K"])
    for x, y in [(4, 4), (7, 4), (10, 4), (12, 6), (3, 7), (12, 9), (5, 11), (9, 11)]:
        s.px(x, y, C["W"]) if y < 6 else s.px(x, y, C["t"])
    # loose end
    s.line(13, 11, 15, 14, C["K"]); s.px(14, 13, C["T"]); s.px(15, 15, C["K"])
    return s

